def rows(dataset, config):
    url = f"https://datasets-server.huggingface.co/rows?dataset={dataset}&config={config}&split=train&offset=500&length=100"
    return json.load(urllib.request.urlopen(url, timeout=60))["rows"]


def main():
    new = []
    for i, t in enumerate(GENERAL_TOPICS):
        new.append({"d": "general", "p": GENERAL_FORMS[i % 3].format(t=t), "think": False})
    for r in rng.sample(rows("sbintuitions%2FJCommonsenseQA", "default"), 14):
        r = r["row"]
        ch = "・".join(r[f"choice{i}"] for i in range(5))
        new.append({"d": "general", "p": f"次の問いに答え、なぜその答えになるのかを日本語で 3 文で説明してください。\n問い：{r['question']}\n選択肢：{ch}", "think": False})
    for r in rng.sample(rows("sbintuitions%2FJEMHopQA", "v1.1"), 14):
        new.append({"d": "general", "p": f"次の問いに、根拠となる事実を順に示してから答えてください。\n問い：{r['row']['question']}", "think": False})
    new += [{"d": "reasoning", "p": p, "think": False} for p in REASONING]
    new += [{"d": "planner", "p": p, "think": False} for p in PLANNER]
    (HERE / "added_prompts.json").write_text(json.dumps(new, ensure_ascii=False, indent=2), encoding="utf-8")
    print(len(new))


if __name__ == "__main__":
    main()
